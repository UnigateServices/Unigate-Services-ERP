export function masterErrorMessage(error: unknown) {
  if (error instanceof ApiError) {
    if (error.message && error.message !== error.code && !/^[A-Z0-9_]+$/.test(error.message)) {
      return error.message;
    }
    return ERRORS[error.code || 'REQUEST_FAILED'] || ERRORS.REQUEST_FAILED;
  }
  return ERRORS.REQUEST_FAILED;
}

export function statusLabel(status: RecordStatus) {
  return status === 'ACTIVE' ? 'نشط' : 'موقوف';
}
